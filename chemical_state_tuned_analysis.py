print("Are multi-hour departure blocks genuine or random artifacts?")
print("=" * 80)

# Compute observed block lengths
chemical_regime_departure_labels = df_results['is_chemical_regime_departure'].values
departure_rate = chemical_regime_departure_labels.mean()

# Find contiguous blocks of departures
block_lengths = []
current_length = 0
for val in chemical_regime_departure_labels:
    if val == 1:
        current_length += 1
    else:
        if current_length > 0:
            block_lengths.append(current_length)
            current_length = 0
if current_length > 0:
    block_lengths.append(current_length)

block_lengths = np.array(block_lengths)

# Under Bernoulli(p), the expected geometric distribution of run lengths
# P(run = k) = p^(k-1) * (1-p) * p  ... actually:
# For consecutive 1s in Bernoulli sequence, run length follows geometric(1-p)
# Expected run length = 1 / (1-p)
# P(run >= k) = p^(k-1)

expected_run = 1 / (1 - departure_rate)
expected_median = np.log(2) / np.log(1/departure_rate) if departure_rate > 0 else 0

# Simulate null distribution of block lengths
n_sim = 1000
null_max_blocks = np.zeros(n_sim)
null_mean_blocks = np.zeros(n_sim)
null_n_long_blocks = np.zeros(n_sim)  # blocks >= 24 hours

for i in range(n_sim):
    sim_labels = np.random.binomial(1, departure_rate, size=len(chemical_regime_departure_labels))
    sim_blocks = []
    curr = 0
    for val in sim_labels:
        if val == 1:
            curr += 1
        else:
            if curr > 0:
                sim_blocks.append(curr)
                curr = 0
    if curr > 0:
        sim_blocks.append(curr)

    if len(sim_blocks) > 0:
        null_max_blocks[i] = max(sim_blocks)
        null_mean_blocks[i] = np.mean(sim_blocks)
        null_n_long_blocks[i] = sum(1 for b in sim_blocks if b >= 24)
    else:
        null_max_blocks[i] = 0
        null_mean_blocks[i] = 0
        null_n_long_blocks[i] = 0

