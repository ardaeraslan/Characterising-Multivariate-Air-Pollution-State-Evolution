# VALIDATION 2: TEMPORAL CLUSTERING TEST
# =============================================================================
#
# THE CONCERN: Even if the departure rate is genuine, are the multi-hour
# REGIONS (24-155 hour blocks) genuine temporal clusters, or would random
# point labelling produce similar block lengths?
#
# Under a Bernoulli(p) null where p = departure rate, the expected run
# length of consecutive departures follows a geometric distribution.
# If observed block lengths greatly exceed geometric expectations, the
# temporal clustering is genuine.
# =============================================================================

print(f"\n{'=' * 80}")
