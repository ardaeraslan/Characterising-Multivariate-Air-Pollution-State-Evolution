class ChemistryVAE(keras.Model):
    """
    VAE for atmospheric chemical state departure detection.

    Architecture (Tuned):
        Encoder: Conv1D(128) → Conv1D(128) → MaxPool → Dropout →
                 3× Bidirectional GRU(32) → Dense(128) → z_mean, z_log_var
        Decoder: Dense(128) → Dense(24×16) → Reshape →
                 2× Unidirectional GRU(32) → Conv1D(128) → Conv1D(16) → reconstruction

    Key changes from original:
        - Unidirectional decoder (prevents bypassing latent bottleneck)
        - ELU activation (smooth negative regime for chemistry ratios)
        - Deeper encoder (3 GRU layers vs 2)
        - Wider conv entry (128 filters) with narrower exit (16 filters)
        - Less dropout (0.05/0.1 — training data diversity is sufficient)
        - Very light static KL (5.24e-6 — reconstruction fidelity priority)
    """

    def __init__(self, input_dim, time_steps, latent_dim=LATENT_DIM):
        super(ChemistryVAE, self).__init__()
        self.latent_dim = latent_dim
        self.time_steps = time_steps
        self.input_dim = input_dim

        self.kl_weight = tf.Variable(KL_WEIGHT, trainable=False, dtype=tf.float32)

        self.encoder = self._build_encoder()
        self.decoder = self._build_decoder()

    def _build_encoder(self):
        encoder_inputs = keras.Input(shape=(self.time_steps, self.input_dim))

        # ─── Conv1D Block (single block, wide→narrow) ───
        # Two Conv1D layers with wide filters to capture multivariate patterns
        x = layers.Conv1D(CONV_FILTERS_1, 3, activation=ACTIVATION, padding='same')(encoder_inputs)
        x = layers.BatchNormalization()(x)
        x = layers.Conv1D(CONV_FILTERS_1, 3, activation=ACTIVATION, padding='same')(x)
        x = layers.MaxPooling1D(2)(x)  # 24 → 12
        x = layers.Dropout(DROPOUT_CONV)(x)

        # ─── Bidirectional GRU Stack (3 layers) ───
        # Deeper temporal encoding — sees both forward and backward context
        for gru_idx in range(N_GRU_LAYERS_ENC):
            return_seq = (gru_idx < N_GRU_LAYERS_ENC - 1)  # Last layer → single vector
            x = layers.Bidirectional(layers.GRU(GRU_UNITS, return_sequences=return_seq))(x)

        # ─── Dense Bottleneck → Latent Space ───
        x = layers.Dense(DENSE_BOTTLENECK_DIM, activation=ACTIVATION)(x)
        x = layers.BatchNormalization()(x)
        x = layers.Dropout(DROPOUT_DENSE)(x)

        z_mean = layers.Dense(self.latent_dim, name='z_mean')(x)
        z_log_var = layers.Dense(self.latent_dim, name='z_log_var')(x)

        return keras.Model(encoder_inputs, [z_mean, z_log_var], name='encoder')

    def _build_decoder(self):
        latent_inputs = keras.Input(shape=(self.latent_dim,))

        # ─── Dense Expansion ───
        x = layers.Dense(DENSE_BOTTLENECK_DIM, activation=ACTIVATION)(latent_inputs)
        x = layers.BatchNormalization()(x)
        x = layers.Dropout(DROPOUT_DENSE)(x)

        x = layers.Dense(self.time_steps * CONV_FILTERS_2, activation=ACTIVATION)(x)
        x = layers.Reshape((self.time_steps, CONV_FILTERS_2))(x)

        # ─── Unidirectional GRU Stack (2 layers) ───
        # CRITICAL: Unidirectional prevents decoder from bypassing the latent
        # bottleneck through backward temporal correlations. Every top-performing
        # VAE anomaly detection paper uses unidirectional decoders:
        # OmniAnomaly (Su et al., KDD 2019), LSTM-VAE (Park et al., 2018),
        # GGM-VAE (Guo et al., ACML 2018), LW-LSTM-VAE (Kayan et al., 2022).
        for gru_idx in range(N_GRU_LAYERS_DEC):
            x = layers.GRU(GRU_UNITS, return_sequences=True)(x)

        # ─── Conv1D Refinement ───
        x = layers.Conv1D(CONV_FILTERS_1, 3, activation=ACTIVATION, padding='same')(x)
        x = layers.BatchNormalization()(x)
        x = layers.Conv1D(CONV_FILTERS_2, 3, activation=ACTIVATION, padding='same')(x)

        # ─── Output: reconstruction ───
        decoder_output = layers.TimeDistributed(
            layers.Dense(self.input_dim, activation='linear')
        )(x)

        return keras.Model(latent_inputs, decoder_output, name='decoder')

    def reparameterize(self, z_mean, z_log_var):
        epsilon = tf.random.normal(shape=tf.shape(z_mean))
        return z_mean + tf.exp(0.5 * z_log_var) * epsilon

    def call(self, inputs, training=None):
        z_mean, z_log_var = self.encoder(inputs, training=training)
        z = self.reparameterize(z_mean, z_log_var)
        reconstruction = self.decoder(z, training=training)

        # KL divergence (static weight — tuning showed static beats cyclical)
        kl_loss = -0.5 * tf.reduce_mean(
            tf.reduce_sum(1 + z_log_var - tf.square(z_mean) - tf.exp(z_log_var), axis=1)
        )
        self.add_loss(self.kl_weight * kl_loss)

        return reconstruction

