# FIG 9 — BRF Feature Importance
# ═══════════════════════════════════════════════════════════════════════
def fig_brf_importance(imps, fnames_brf, met_pct, temp_pct):
    # Combine sin/cos pairs for cyclical temporal features into single metrics
    import collections
    combined_imps = collections.OrderedDict()
    for name, imp in zip(fnames_brf, imps):
        base = name.replace('(sin)', '').replace('(cos)', '').strip()
        if '(sin)' in name or '(cos)' in name:
            base_label = base  # e.g. 'Hour of Day', 'Day of Week', 'Month'
        else:
            base_label = name
        combined_imps[base_label] = combined_imps.get(base_label, 0) + imp
    cnames = list(combined_imps.keys())
    cimps = np.array(list(combined_imps.values()))
    si = np.argsort(cimps); sn = [cnames[i] for i in si]; sv = cimps[si]
    met_set = {'Wind Direction','Wind Speed','Air Temperature','Boundary Layer Height'}
    cols = [TEAL if n in met_set else PURPLE for n in sn]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 5.5), gridspec_kw={'width_ratios': [3, 1]})
    ax1.barh(range(len(sv)), sv, color=cols, alpha=0.85, edgecolor='white')
    ax1.set_yticks(range(len(sn))); ax1.set_yticklabels(sn, fontsize=9)
    ax1.set_xlabel('Feature Importance (Gini)', fontsize=12)
    ax1.set_title('(a) BRF Feature Importance — London Marylebone Road (MY1) | 2022–2025', fontsize=11)
    for i, v in enumerate(sv): ax1.text(v+0.003, i, f'{v:.3f}', va='center', fontsize=8)
    ax1.legend(handles=[Patch(facecolor=TEAL, label='Meteorological'),
                         Patch(facecolor=PURPLE, label='Temporal')], loc='lower right', fontsize=8)
    ax2.pie([met_pct, temp_pct], labels=['Meteorological','Temporal'], colors=[TEAL, PURPLE],
            autopct='%1.1f%%', startangle=90, wedgeprops=dict(edgecolor='white', linewidth=2),
            textprops={'fontsize': 10})
    ax2.set_title('(b) Met. vs Temporal')
    plt.tight_layout(); plt.savefig('Fig9_BRF_Importance.png'); plt.show()
 
 
