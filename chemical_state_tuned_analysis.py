def compute_jaccard_matrix():
    """Compute 4x4 Jaccard similarity matrix between all detection method pairs.
    Jaccard = |A ∩ B| / |A ∪ B| — a value of 1 means perfect overlap, 0 means no overlap.
    Added in response to reviewer comment on inter-method correlation.
    """
    methods = {
        'VAE Error':   chemical_regime_departure_vae,
        'Recon. Prob.': chemical_regime_departure_prob,
        'Iso. Forest':  chemical_regime_departure_iso,
        'Z-score':      chemical_regime_departure_statistical,
    }
    names = list(methods.keys())
    arrays = [methods[n].astype(bool) for n in names]
    print("\n" + "=" * 60)
    print("PAIRWISE JACCARD SIMILARITY MATRIX (4 detection methods)")
    print("  Jaccard(A,B) = |A∩B| / |A∪B|  (1=identical, 0=no overlap)")
    print("=" * 60)
    header = f"{'':>14}" + "".join(f"{n:>14}" for n in names)
    print(header)
    for i, ni in enumerate(names):
        row = f"{ni:>14}"
        for j, nj in enumerate(names):
            inter = np.sum(arrays[i] & arrays[j])
            union = np.sum(arrays[i] | arrays[j])
            jac = inter / union if union > 0 else 0.0
            row += f"{jac:>14.3f}"
        print(row)
    print()
    # Also print raw co-occurrence counts
    print("RAW CO-OCCURRENCE COUNTS (sequences flagged by BOTH methods):")
    print(header)
    for i, ni in enumerate(names):
        row = f"{ni:>14}"
        for j, nj in enumerate(names):
            inter = np.sum(arrays[i] & arrays[j])
            row += f"{inter:>14}"
        print(row)

def classify_per_pollutant(data, thresholds, pollutant_columns):
    """
    For each pollutant, compute the fraction of hours that fall within
    ±1σ of the normal mean (i.e., "pattern/chemistry" for that pollutant).
    Returns dict of {pollutant: fraction_within_range}.
    """
    results = {}
    for col in pollutant_columns:
        within = ((data[col] >= thresholds[col]['low']) &
                  (data[col] <= thresholds[col]['high']))
        results[col] = within.mean()
    return results

