def fig_met_attribution(ds, rate_pct):
    """ds = hourly dataset with wd/ws/air_temp/blh + is_chemical_regime_departure."""
    dep = ds[ds['is_chemical_regime_departure']==1]; norm = ds[ds['is_chemical_regime_departure']==0]
    sectors = ['N','NE','E','SE','S','SW','W','NW']
    ds = ds.copy()
    ds['sector'] = ((ds['wd']+22.5)%360/45).astype(int).map(dict(enumerate(sectors)))
    ds['hour'] = ds.index.hour; ds['month'] = ds.index.month
 
    fig, axes = plt.subplots(4, 3, figsize=(18, 22))
 
    # Row 0: distributions
    nf = ds[ds['is_chemical_regime_departure']==0]['sector'].value_counts(normalize=True)*100
    df_ = ds[ds['is_chemical_regime_departure']==1]['sector'].value_counts(normalize=True)*100
    x = np.arange(8); w = 0.35
    axes[0,0].bar(x-w/2,[nf.get(s,0) for s in sectors],w,color=TEAL,alpha=0.85,label='Normal')
    axes[0,0].bar(x+w/2,[df_.get(s,0) for s in sectors],w,color=CORAL,alpha=0.85,label='Departed')
    axes[0,0].set_xticks(x); axes[0,0].set_xticklabels(sectors)
    axes[0,0].set_ylabel('Frequency (%)'); axes[0,0].set_title('(a) Wind Direction'); axes[0,0].legend(fontsize=7)
 
    for ax, col, xlabel, title in [
        (axes[0,1], 'ws', 'Wind Speed (m/s)', '(b) Wind Speed'),
        (axes[0,2], 'air_temp', 'Temperature (°C)', '(c) Temperature'),
        (axes[1,0], 'blh', 'BLH (m)', '(d) Boundary Layer Height')]:
        ax.hist(norm[col].dropna(), bins=30, color=TEAL, alpha=0.5, density=True, label='Normal')
        ax.hist(dep[col].dropna(), bins=30, color=CORAL, alpha=0.5, density=True, label='Departed')
        ax.set_xlabel(xlabel); ax.set_title(title); ax.legend(fontsize=7)
 
    # Rate by bins
    def rate_bars(ax, col, bins, labels, xlabel, title):
        ds[f'{col}_b'] = pd.cut(ds[col], bins=bins, labels=labels)
        r = ds.groupby(f'{col}_b')['is_chemical_regime_departure'].mean()*100
        bc = [CORAL if v > rate_pct else TEAL for v in r.values]
        ax.bar(range(len(r)), r.values, color=bc, alpha=0.85)
        ax.axhline(y=rate_pct, color=GREY, ls='--')
        ax.set_xticks(range(len(labels))); ax.set_xticklabels(labels, fontsize=7, rotation=30)
        ax.set_xlabel(xlabel); ax.set_ylabel('Departure Rate (%)'); ax.set_title(title)
 
