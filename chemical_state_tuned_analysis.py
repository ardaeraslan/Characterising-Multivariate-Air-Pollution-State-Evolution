# ─── Tuned Chemistry-Aware Loss Function ───
def chemistry_aware_loss(y_true, y_pred):
    """
    Domain-specific loss for atmospheric chemistry departure detection.

    Tuned weights (from Optuna):
      - Base reconstruction: 1.0 (always present)
      - Pollutant emphasis:  0.2  (was 0.3 — raw pollutants still important)
      - Ratio emphasis:      0.05 (was 0.2 — ratios derive from pollutants,
                                    double-counting reduced)
      - Gradient emphasis:   0.15 (was 0.3 — temporal changes still matter)
      - Low-value penalty:   2.5  (was 2.0 — slightly more sensitivity to
                                    near-zero concentrations)

    Feature layout (19 features from df_scaled):
        [0:7]   Raw pollutants:  co, no2, no, o3, so2, pm10, pm2.5
        [7:12]  Chemistry ratios: no2_nox_ratio, co_nox_ratio, pm2.5_pm10_ratio, ox, PSS
        [12:19] Gradients:       co_grad, no2_grad, no_grad, o3_grad, so2_grad, pm10_grad, pm2.5_grad
    """
    # 1. Base reconstruction loss (all 19 features)
    reconstruction_loss = tf.reduce_mean(tf.square(y_true - y_pred))

    # 2. Pollutant-specific loss with low-concentration penalty
    pollutant_true = y_true[:, :, :7]
    pollutant_pred = y_pred[:, :, :7]
    low_value_mask = tf.abs(pollutant_true) < 0.5
    low_value_weights = tf.where(low_value_mask, LOW_VALUE_WEIGHT, 1.0)
    weighted_pollutant_loss = tf.reduce_mean(
        tf.square(pollutant_true - pollutant_pred) * low_value_weights
    )

    # 3. Chemistry ratio loss
    ratio_loss = tf.reduce_mean(
        tf.square(y_true[:, :, 7:12] - y_pred[:, :, 7:12])
    )

    # 4. Gradient loss
    gradient_loss = tf.reduce_mean(
        tf.square(y_true[:, :, 12:19] - y_pred[:, :, 12:19])
    )

    # Combined: base + tuned weighted components
    total_loss = (
        reconstruction_loss +
        LOSS_WEIGHT_POLLUTANT * weighted_pollutant_loss +
        LOSS_WEIGHT_RATIO * ratio_loss +
        LOSS_WEIGHT_GRADIENT * gradient_loss
    )

    return total_loss

