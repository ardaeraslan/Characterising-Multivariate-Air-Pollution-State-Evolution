print(f"    Max:    {block_lengths.max()} hours")
print(f"    Blocks ≥ 24 hours: {sum(block_lengths >= 24)}")

print(f"\n  Under random Bernoulli({departure_rate:.3f}) null:")
print(f"    Expected mean run: {expected_run:.1f} hours")
print(f"    Simulated max block: {null_max_blocks.mean():.1f} ± {null_max_blocks.std():.1f}")
print(f"    Simulated blocks ≥ 24h: {null_n_long_blocks.mean():.1f} ± {null_n_long_blocks.std():.1f}")

p_max = (null_max_blocks >= block_lengths.max()).mean()
p_n_long = (null_n_long_blocks >= sum(block_lengths >= 24)).mean()

print(f"\n  P-value (max block ≥ {block_lengths.max()}h): {p_max:.4f}")
print(f"  P-value (≥{sum(block_lengths >= 24)} blocks of ≥24h): {p_n_long:.4f}")

