"""## COVID-19 LOCKDOWN CASE STUDY #####

 This code applies the VAE (trained on 2015-2019) to the COVID lockdown period
 (March 2020 – June 2021) as a VALIDATION exercise.

 The model was never told about COVID. If it correctly flags specific featrues that are known to caused chemical regime departures during lockdown — when we independently know pollution patterns were
 massively disrupted (NO2 fell ~50%, traffic dropped 69%) — this provides
 strong evidence the system detects genuine atmospheric chemistry regime changes.

 Prerequisites (from Preprocessing + DL Algorithm):
   - vae: trained ChemistryVAE model (trained on 2015-2019)
   - x_train, x_covid: sequence arrays
   - sigma2: empirical variance from training residuals (shape: 24, 19)
   - threshold_vae: VAE error threshold from training 97th percentile
   - threshold_prob: reconstruction probability threshold from training 97th percentile
   - train_grad_mean, train_grad_std: gradient statistics from training period
   - df_autoencoder_train, df_autoencoder_covid: raw pollutant DataFrames
   - df_scaled_covid, df_covid_enhanced: scaled/enhanced DataFrames for COVID period
   - iso_forest: IsolationForest fitted on training data
   - All variables from Preprocessing_Temporal_Split.py and chemical_regime_departure_Labelling.py

#####1. RECONSTRUCTION ERRORS ON COVID DATA
"""

print("\n" + "=" * 60)
print("COVID-19 LOCKDOWN CASE STUDY")
print("=" * 60)
print("Applying VAE trained on 2015-2019 to March 2020 – June 2021")
print("The model has NEVER seen this data.\n")

# Reconstruct COVID sequences
x_covid_pred = vae.predict(x_covid, verbose=0)

# Reconstruction errors (same feature groups as test evaluation)
pollutant_indices = list(range(7))
ratio_indices = list(range(7, 12))
gradient_indices = list(range(12, 19))

covid_pollutant_errors = np.mean(np.abs(x_covid[:, :, pollutant_indices] -
                                         x_covid_pred[:, :, pollutant_indices]), axis=(1, 2))
covid_ratio_errors = np.mean(np.abs(x_covid[:, :, ratio_indices] -
                                     x_covid_pred[:, :, ratio_indices]), axis=(1, 2))
covid_gradient_errors = np.mean(np.abs(x_covid[:, :, gradient_indices] -
                                        x_covid_pred[:, :, gradient_indices]), axis=(1, 2))

covid_vae_errors = (0.50 * covid_pollutant_errors +
                    0.05 * covid_ratio_errors +
                    0.15 * covid_gradient_errors)

# Compare with training baseline
print(f"{'':20s} {'Training':>15s} {'COVID':>15s} {'Ratio':>10s}")
print(f"{'Pollutant MAE':20s} {np.mean(train_pollutant_errors):15.6f} {np.mean(covid_pollutant_errors):15.6f} {np.mean(covid_pollutant_errors)/np.mean(train_pollutant_errors):10.2f}x")
print(f"{'Ratio MAE':20s} {np.mean(train_ratio_errors):15.6f} {np.mean(covid_ratio_errors):15.6f} {np.mean(covid_ratio_errors)/np.mean(train_ratio_errors):10.2f}x")
print(f"{'Gradient MAE':20s} {np.mean(train_gradient_errors):15.6f} {np.mean(covid_gradient_errors):15.6f} {np.mean(covid_gradient_errors)/np.mean(train_gradient_errors):10.2f}x")
print(f"{'Weighted Overall':20s} {np.mean(train_vae_errors):15.6f} {np.mean(covid_vae_errors):15.6f} {np.mean(covid_vae_errors)/np.mean(train_vae_errors):10.2f}x")

"""#####2. RECONSTRUCTION PROBABILITY ON COVID DATA"""

print(f"\nComputing Monte Carlo reconstruction probability (L={L} samples)...")

z_mean_covid, z_log_var_covid = vae.encoder.predict(x_covid, verbose=0)
n_covid_sequences = len(x_covid)

covid_total_ll = np.zeros(n_covid_sequences)
covid_per_feature_ll = np.zeros((n_covid_sequences, n_features))

for l in range(L):
    if (l + 1) % 10 == 0:
        print(f"  Sample {l+1}/{L}")

    epsilon = np.random.normal(size=z_mean_covid.shape).astype(np.float32)
    z_sample = z_mean_covid + np.exp(0.5 * z_log_var_covid) * epsilon
    recon = vae.decoder.predict(z_sample, verbose=0)

    # Use TRAINING σ² — same baseline as test evaluation
    log_likelihood = -0.5 * (
        np.log(2 * np.pi) +
        np.log(sigma2) +
        np.square(x_covid - recon) / sigma2
    )

    per_feature_ll = np.sum(log_likelihood, axis=1)
    sample_ll = np.sum(per_feature_ll, axis=1)

    covid_total_ll += sample_ll
    covid_per_feature_ll += per_feature_ll

covid_recon_prob_scores = -(covid_total_ll / L)
covid_per_feature_scores = -(covid_per_feature_ll / L)

