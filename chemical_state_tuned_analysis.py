def add_chemistry_features(df):
    """
    Add chemistry-aware features to a single continuous period of data.
    Computed separately per period so gradients and rolling stats
    don't leak across temporal boundaries.
    """
    df_enhanced = df.copy()

    # Safe division to avoid division by zero
    epsilon = 1e-10

    # Chemical ratios (using nox which is in the dataframe)
    df_enhanced['no2_nox_ratio'] = (df['no2'] / (df['nox'] + epsilon)).clip(-10, 10)
    df_enhanced['co_nox_ratio'] = (df['co'] / (df['nox'] + epsilon)).clip(-10, 10)
    df_enhanced['pm2.5_pm10_ratio'] = (df['pm2.5'] / (df['pm10'] + epsilon)).clip(-10, 10)

    # Ox (total oxidant) and photostationary state
    df_enhanced['ox'] = df['no2'] + df['o3']
    df_enhanced['PSS'] = (df['no2'] / ((df['o3'] * df['no']) + epsilon)).clip(-10, 10)

    # Gradients (rate of change) — computed on the 7 VAE pollutants only
    for col in pollutant_columns:
        df_enhanced[f'{col}_gradient'] = np.gradient(df[col].fillna(method='ffill').fillna(method='bfill').values)

    # Fill remaining NaN
    df_enhanced = df_enhanced.fillna(method='bfill').fillna(method='ffill').fillna(0)

    return df_enhanced

